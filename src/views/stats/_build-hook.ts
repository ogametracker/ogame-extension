import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { StatsRouteConfig } from './router/config';

interface StatsRoute extends StatsRouteConfig {
    name: string;
    path: string;
    componentPath: string;
    children?: StatsRoute[];
}

const root = fileURLToPath(new URL('./views', import.meta.url));
const output = new URL('./router/routes.generated.ts', import.meta.url);

async function readConfig(directory: string, filename: string, isIndex: boolean): Promise<StatsRouteConfig> {
    const configNames = isIndex ? ['route-config.ts', `route-config.${filename}.ts`] : [`route-config.${filename}.ts`];
    const config = configNames.map(name => join(directory, name)).find(file => existsSync(file));
    return config == null ? {} : (await import(pathToFileURL(config).href)).default;
}

async function collectRoutes(directory: string, segments: string[]): Promise<StatsRoute[]> {
    const entries = readdirSync(directory, { withFileTypes: true });
    const files = entries.filter(entry => entry.isFile() && entry.name.endsWith('.vue'));
    const directories = entries.filter(entry => entry.isDirectory());
    const routes: StatsRoute[] = [];

    for (const file of files) {
        const filename = basename(file.name, '.vue');
        const isIndex = filename.toLowerCase() === 'index';
        if (isIndex && segments.length > 0) {
            continue;
        }

        const routeSegments = isIndex ? segments : [...segments, filename];
        const route = {
            ...await readConfig(directory, filename, isIndex),
            name: routeSegments.join('/').toLowerCase(),
            path: isIndex ? '/' : filename.toLowerCase(),
            componentPath: ['../views', ...segments, file.name].join('/'),
        };
        routes.push(route);
    }

    const nestedRoutes: StatsRoute[] = [];
    for (const child of directories) {
        const childDirectory = join(directory, child.name);
        const childSegments = [...segments, child.name];
        const index = readdirSync(childDirectory).find(file => file.toLowerCase() === 'index.vue');
        if (!index) {
            throw new Error(`Missing route index in ${childDirectory}`);
        }

        const children = await collectRoutes(childDirectory, childSegments);
        nestedRoutes.push({
            ...await readConfig(childDirectory, basename(index, '.vue'), true),
            name: childSegments.join('/').toLowerCase(),
            path: child.name.toLowerCase(),
            componentPath: ['../views', ...childSegments, index].join('/'),
            ...(children.length ? { children } : {}),
        });
    }

    if (segments.length === 0) {
        const index = routes.find(route => route.path === '/');
        if (!index) {
            throw new Error('Missing Stats root route');
        }
        index.children = [...routes.filter(route => route !== index), ...nestedRoutes];
        return [index];
    }

    return [...routes, ...nestedRoutes];
}

function printRoutes(routes: StatsRoute[], depth: number): string {
    const indent = '    '.repeat(depth);
    const fieldIndent = indent + '    ';
    const blocks = routes.map(({ componentPath, children, ...record }) => {
        const fields = Object.entries(record).map(([key, value]) => `${fieldIndent}${key}: ${JSON.stringify(value)},`);
        fields.push(`${fieldIndent}component: () => import(${JSON.stringify(componentPath)}),`);
        if (children) {
            fields.push(`${fieldIndent}children: ${printRoutes(children, depth + 2)},`);
        }
        return `${indent}{\n${fields.join('\n')}\n${indent}},`;
    });
    return `[\n${blocks.join('\n')}\n${'    '.repeat(depth - 1)}]`;
}

async function generateRoutes() {
    const routes = await collectRoutes(root, []);
    writeFileSync(output, `// Generated by _build-hook.ts.\nimport type { RouteRecordRaw } from 'vue-router';\n\nexport default ${printRoutes(routes, 1)} satisfies RouteRecordRaw[];\n`);
}

void generateRoutes().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
